export function isReservedPearlWord(word: string): boolean {
    return RESERVED_WORDS.has(word);
}

/** The PEARL grammar requires an ASCII letter as the first character. */
export function isValidPearlIdentifier(word: string): boolean {
    return /^[A-Za-z][A-Za-z0-9_]*$/.test(word) && !isReservedPearlWord(word);
}
